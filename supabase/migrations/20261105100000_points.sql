-- P4b-05: points are a separate, append-only ledger (R-PTS-7). Value is stored
-- in cents and shown as cents / 10, so S$0.10 is one point and nothing rounds.
-- Earning stays off until the owner sets a weekly cap and a minimum account age
-- and turns on points.earning (owner, 1 Nov). Those two settings have no row yet.

insert into public.feature_flags (key, enabled, description) values
  ('points.earning', false, 'Points earned from playing. Off until the owner sets the cap and account age (Q13).');

insert into public.app_settings (key, value, description) values
  ('points.earn_multiplier', '2', 'Value earned for each cent of fee paid'),
  ('points.expiry_months', '12', 'Months before earned points lapse (R-PTS-4)'),
  ('points.min_confirmed_matches', '5', 'Confirmed matches before earning (R-PTS-6)');

-- A value or nothing, for settings the owner hasn't set.
create function private.setting_int_or_null(p_key text) returns integer
language sql stable security definer set search_path = '' as $$
  -- Definer: callers include roles that may not read app_settings directly.
  select (value #>> '{}')::int from public.app_settings where key = p_key;
$$;
revoke execute on function private.setting_int_or_null(text) from public, anon, authenticated;

create table public.points_entries (
  id bigint generated by default as identity primary key,
  user_id uuid not null,
  kind text not null check (kind in ('earn', 'reverse', 'spend', 'return', 'expire', 'forfeit')),
  amount_minor bigint not null check (amount_minor <> 0),
  lot_id bigint not null,
  expires_at timestamptz not null,
  source_kind text not null,
  source_id text not null,
  idempotency_key text not null unique,
  created_at timestamptz not null default now()
);
create index points_entries_user_idx on public.points_entries (user_id, lot_id);
create index points_entries_source_idx on public.points_entries (source_kind, source_id);

create trigger points_entries_no_change before update or delete on public.points_entries
  for each row execute function private.forbid_change();
create trigger points_entries_no_truncate before truncate on public.points_entries
  for each statement execute function private.forbid_change();

create table public.points_blocks (
  user_id uuid primary key,
  blocked_by uuid,
  reason text,
  created_at timestamptz not null default now()
);

alter table public.points_entries enable row level security;
alter table public.points_blocks enable row level security;
revoke all on public.points_entries, public.points_blocks from anon, authenticated;

-- What's left in each unexpired lot. A lot can go below zero if earned points
-- were spent and then reversed, and the shortfall lapses with it.
create function private.points_lots(p_user uuid)
returns table (lot_id bigint, expires_at timestamptz, left_minor bigint)
language sql stable security definer set search_path = '' as $$
  -- Definer: points_entries has no client access.
  select e.lot_id, max(e.expires_at), sum(e.amount_minor)::bigint
  from public.points_entries e
  where e.user_id = p_user
  group by e.lot_id
  having max(e.expires_at) > now();
$$;

create function private.points_balance(p_user uuid) returns bigint
language sql stable security definer set search_path = '' as $$
  -- Definer: reads private lots.
  select greatest(coalesce(sum(left_minor), 0), 0)::bigint from private.points_lots(p_user);
$$;

-- Oldest lots first. The caller holds the buyer's advisory lock.
create function private.points_spend(p_user uuid, p_amount bigint, p_source_kind text, p_source_id text)
returns void
language plpgsql security definer set search_path = '' as $$
-- Definer: writes the points ledger.
declare
  l record;
  v_left bigint := p_amount;
  v_take bigint;
begin
  if p_amount <= 0 then return; end if;
  if private.points_balance(p_user) < p_amount then
    raise exception 'You don''t have that many points.';
  end if;
  for l in
    select * from private.points_lots(p_user) x where x.left_minor > 0 order by x.expires_at, x.lot_id
  loop
    exit when v_left = 0;
    v_take := least(v_left, l.left_minor);
    insert into public.points_entries (user_id, kind, amount_minor, lot_id, expires_at, source_kind,
      source_id, idempotency_key)
    values (p_user, 'spend', -v_take, l.lot_id, l.expires_at, p_source_kind, p_source_id,
      'spend:' || p_source_kind || ':' || p_source_id || ':' || l.lot_id);
    v_left := v_left - v_take;
  end loop;
  if v_left > 0 then raise exception 'You don''t have that many points.'; end if;
end;
$$;

-- Back to the lots they came from, with their original expiry (Q87 default).
create function private.points_return(p_source_kind text, p_source_id text, p_key text,
  p_amount bigint default null)
returns bigint
language plpgsql security definer set search_path = '' as $$
-- Definer: writes the points ledger.
declare
  s record;
  v_left bigint;
  v_take bigint;
  v_back bigint := 0;
begin
  -- A block forfeits points, including any on their way back.
  if exists (select 1 from public.points_blocks b join public.points_entries e on e.user_id = b.user_id
      where e.source_kind = p_source_kind and e.source_id = p_source_id) then
    return 0;
  end if;
  select coalesce(sum(-amount_minor) filter (where kind = 'spend'), 0)
       - coalesce(sum(amount_minor) filter (where kind = 'return'), 0)
  into v_left
  from public.points_entries where source_kind = p_source_kind and source_id = p_source_id;
  if p_amount is not null then v_left := least(v_left, p_amount); end if;
  for s in
    select e.user_id, e.lot_id, max(e.expires_at) as expires_at, sum(e.amount_minor) as open_minor
    from public.points_entries e
    where e.source_kind = p_source_kind and e.source_id = p_source_id and e.kind in ('spend', 'return')
    group by e.user_id, e.lot_id
    having sum(e.amount_minor) < 0
    order by e.lot_id desc
  loop
    exit when v_left <= 0;
    v_take := least(v_left, -s.open_minor);
    insert into public.points_entries (user_id, kind, amount_minor, lot_id, expires_at, source_kind,
      source_id, idempotency_key)
    values (s.user_id, 'return', v_take, s.lot_id, s.expires_at, p_source_kind, p_source_id,
      'return:' || p_source_kind || ':' || p_source_id || ':' || s.lot_id || ':' || p_key)
    on conflict (idempotency_key) do nothing;
    if found then
      v_left := v_left - v_take;
      v_back := v_back + v_take;
    end if;
  end loop;
  return v_back;
end;
$$;

-- Redeeming needs the owner's minimum age to exist and be met.
create function private.points_can_redeem(p_user uuid) returns boolean
language sql stable security definer set search_path = '' as $$
  -- Definer: reads settings and blocks.
  select private.setting_int_or_null('points.redeem_min_account_days') is not null
    and not exists (select 1 from public.points_blocks b where b.user_id = p_user)
    -- Not profiles.created_at: a client can write that.
    and exists (select 1 from auth.users u where u.id = p_user and u.created_at
      <= now() - make_interval(days => private.setting_int_or_null('points.redeem_min_account_days')));
$$;

-- Keeps a payment's points equal to what it should earn. Taking points back
-- always works. Giving them needs every gate. A payment the weekly cap cut short
-- catches up only if something touches it again.
create function private.points_sync(p_payment uuid) returns void
language plpgsql security definer set search_path = '' as $$
-- Definer: writes the points ledger.
declare
  pay public.payments;
  v_present boolean := false;
  v_target bigint := 0;
  v_now bigint;
  v_delta bigint;
  v_cap int;
  v_week bigint;
  v_lot bigint;
  v_n int;
begin
  select * into pay from public.payments where id = p_payment;
  if pay.id is null or pay.purpose not in ('meet', 'ticket', 'tournament', 'host_spot')
     or pay.status <> 'succeeded' then
    return;
  end if;
  perform pg_advisory_xact_lock(hashtext('points:' || pay.user_id));
  if pay.purpose = 'ticket' then
    v_present := exists (select 1 from public.event_tickets t
      where t.activity_id = pay.activity_id and t.user_id = pay.user_id and t.scanned_at is not null);
  else
    v_present := exists (select 1 from public.activity_participants ap
      where ap.activity_id = pay.activity_id and ap.user_id = pay.user_id and ap.attendance = 'present');
  end if;
  -- A lost chargeback gave the fee back without a refund row.
  if v_present and not exists (select 1 from public.payment_disputes d
      where d.payment_id = pay.id and d.status = 'lost') then
    select (pay.fee_minor - coalesce(sum(r.fee_minor), 0)) * private.setting_int('points.earn_multiplier')
    into v_target
    from public.refunds r where r.payment_id = pay.id and r.status <> 'voided';
  end if;
  select coalesce(sum(amount_minor), 0), count(*) into v_now, v_n
  from public.points_entries
  where source_kind = 'payment' and source_id = pay.id::text and kind in ('earn', 'reverse');
  v_delta := v_target - v_now;
  if v_delta = 0 then return; end if;

  if v_delta < 0 then
    select e.lot_id into v_lot from public.points_entries e
    where e.source_kind = 'payment' and e.source_id = pay.id::text and e.kind = 'earn'
    order by e.id desc limit 1;
    insert into public.points_entries (user_id, kind, amount_minor, lot_id, expires_at, source_kind,
      source_id, idempotency_key)
    select pay.user_id, 'reverse', v_delta, v_lot, max(e.expires_at), 'payment', pay.id::text,
      'earn:' || pay.id || ':' || v_n
    from public.points_entries e where e.lot_id = v_lot;
    return;
  end if;

  v_cap := private.setting_int_or_null('points.weekly_cap_minor');
  if not private.flag('points.earning') or v_cap is null
     or private.setting_int_or_null('points.redeem_min_account_days') is null
     or not private.has_verified_mobile(pay.user_id)
     or exists (select 1 from public.points_blocks b where b.user_id = pay.user_id)
     or (select count(*) from public.match_results m
         where pay.user_id = any (m.side_a || m.side_b)
           and not exists (select 1 from public.match_results n where n.supersedes = m.id))
        < private.setting_int('points.min_confirmed_matches') then
    return;
  end if;
  select coalesce(sum(amount_minor), 0) into v_week from public.points_entries
  where user_id = pay.user_id and kind in ('earn', 'reverse') and created_at > now() - interval '7 days';
  v_delta := least(v_delta, greatest(v_cap - greatest(v_week, 0), 0));
  if v_delta <= 0 then return; end if;

  v_lot := nextval(pg_get_serial_sequence('public.points_entries', 'id'));
  insert into public.points_entries (id, user_id, kind, amount_minor, lot_id, expires_at, source_kind,
    source_id, idempotency_key)
  values (v_lot, pay.user_id, 'earn', v_delta, v_lot,
    now() + make_interval(months => private.setting_int('points.expiry_months')),
    'payment', pay.id::text, 'earn:' || pay.id || ':' || v_n);
end;
$$;

-- Points never get in the way of attendance, tickets or refunds.
create function private.points_touch(p_activity uuid, p_user uuid, p_payment uuid default null) returns void
language plpgsql security definer set search_path = '' as $$
-- Definer: runs from triggers fired by clients.
declare
  r record;
begin
  for r in
    select id from public.payments
    where (p_payment is not null and id = p_payment)
       or (p_payment is null and activity_id = p_activity and user_id = p_user and status = 'succeeded'
           and purpose in ('meet', 'ticket', 'tournament', 'host_spot'))
  loop
    begin
      perform private.points_sync(r.id);
    exception when others then
      perform private.money_alert('points_failed', 'points-failed:' || r.id || ':' || now()::date,
        jsonb_build_object('payment', r.id));
    end;
  end loop;
end;
$$;

create function private.points_dispute() returns trigger
language plpgsql security definer set search_path = '' as $$
-- Definer: fired by the webhook.
begin
  if new.status = 'lost' and old.status is distinct from 'lost' then
    perform private.points_touch(null, null, new.payment_id);
  end if;
  return new;
end;
$$;
create trigger payment_disputes_points after update of status on public.payment_disputes
  for each row execute function private.points_dispute();

create function private.points_attendance() returns trigger
language plpgsql security definer set search_path = '' as $$
-- Definer: fired by a host's update.
begin
  if new.attendance is distinct from old.attendance then
    perform private.points_touch(new.activity_id, new.user_id);
  end if;
  return new;
end;
$$;
create trigger activity_participants_points after update of attendance on public.activity_participants
  for each row execute function private.points_attendance();

create function private.points_ticket() returns trigger
language plpgsql security definer set search_path = '' as $$
