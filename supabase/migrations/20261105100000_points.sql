begin
  if new.scanned_at is distinct from old.scanned_at then
    perform private.points_touch(new.activity_id, new.user_id);
  end if;
  return new;
end;
$$;
create trigger event_tickets_points after update of scanned_at on public.event_tickets
  for each row execute function private.points_ticket();

create function private.points_refund() returns trigger
language plpgsql security definer set search_path = '' as $$
