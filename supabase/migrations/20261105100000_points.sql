-- Lots past their date are already out of every balance. This writes it down.
create function private.points_expire() returns void
language plpgsql security definer set search_path = '' as $$
-- Definer: cron.
declare
  l record;
begin
  for l in
    select e.user_id, e.lot_id, max(e.expires_at) as expires_at, sum(e.amount_minor) as left_minor,
      count(*) as n
    from public.points_entries e
    group by e.user_id, e.lot_id
    having max(e.expires_at) <= now() and sum(e.amount_minor) > 0
  loop
    insert into public.points_entries (user_id, kind, amount_minor, lot_id, expires_at, source_kind,
      source_id, idempotency_key)
    values (l.user_id, 'expire', -l.left_minor, l.lot_id, l.expires_at, 'lot', l.lot_id::text,
      'expire:' || l.lot_id || ':' || l.n)
    on conflict (idempotency_key) do nothing;
  end loop;
end;
$$;
select cron.schedule('points-expire', '40 16 * * *', 'select private.points_expire()');

create function public.points_my() returns jsonb
language sql stable security definer set search_path = '' as $$
  -- Definer: points_entries has no client access. Only the caller's own rows.
  select jsonb_build_object(
    'balance_minor', private.points_balance(auth.uid()),
    'can_redeem', private.points_can_redeem(auth.uid()),
    'earning', private.flag('points.earning'),
    'next_expiry', (select min(l.expires_at) from private.points_lots(auth.uid()) l where l.left_minor > 0),
    'history', (select coalesce(jsonb_agg(x order by x ->> 'at' desc), '[]') from (
      select jsonb_build_object('kind', e.kind, 'amount_minor', e.amount_minor, 'at', e.created_at) as x
      from public.points_entries e
      where e.user_id = auth.uid()
      order by e.id desc limit 50) y));
$$;
revoke execute on function public.points_my() from public, anon;
grant execute on function public.points_my() to authenticated;
